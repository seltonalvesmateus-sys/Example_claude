const PT_SET: ReadonlySet<string> = new Set(PT);
const EN_SET: ReadonlySet<string> = new Set(EN);
const BOTH_SET: ReadonlySet<string> = new Set([...PT, ...EN]);

/** Retorna o conjunto de stopwords do idioma escolhido, ou undefined se nenhum. */
export function getStopwords(language: StopwordLanguage): ReadonlySet<string> | undefined {
  switch (language) {
    case 'pt':
      return PT_SET;
    case 'en':
      return EN_SET;
    case 'both':
      return BOTH_SET;
    default:
      return undefined;
  }
}
